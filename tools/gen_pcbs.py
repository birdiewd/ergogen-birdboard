"""Regenerate the `pcbs:` section of config.yaml (optional maintainer tool).

The Ergogen web UI only reads config.yaml; you never need to run this. It exists
because the PCB list is a matrix: 4 switch types x 1 MCU = 4 PCBs (hotswap only),
which is tedious to keep consistent by hand.

    python3 tools/gen_pcbs.py            # rewrites everything from the `pcbs:` line down

To change a pin, an MCU position or a LED/diode offset, edit the tables below (or the
`units:` block in config.yaml for the offsets) and re-run, or edit config.yaml directly.
"""
import pathlib
import sys

CONFIG = pathlib.Path(__file__).resolve().parent.parent / "config.yaml"

# Net per matrix column / row, in the MCU's own pin names.
MCUS = {
    "zero": dict(
        what="custom/mcu_rp2040_zero", vdd="5V", shift="[mcu_x, mcu_zero_y]",
        pins={"GP0": "outer", "GP1": "pinky", "GP2": "ring", "GP3": "middle", "GP4": "index", "GP5": "inner",
              "GP6": "top", "GP7": "home", "GP8": "bottom", "GP9": "thumb", "GP10": "led_data",
              "GP12": "link"},
        note="Waveshare RP2040-Zero. Matrix on the right edge, thumb and LED data on the bottom row. 3.3V LED data.",
    ),
}
# vdd above is the NET name on that MCU's 5V pin (what the LEDs are powered from):
# RP2040-Zero 5V (param `V5`, default net "5V").

SWITCHES = {
    "mx": dict(what="ceoloide/switch_mx", family="mx", extra=["include_keycap: true"]),
    "lpmx": dict(what="ceoloide/switch_gateron_ks27_ks33", family="lpmx", extra=[]),
    "choc": dict(what="ceoloide/switch_choc_v1_v2", family="choc",
                 extra=["include_keycap: true", "choc_v2_support: false"]),
    "choc2": dict(what="ceoloide/switch_choc_v1_v2", family="choc",
                  extra=["include_keycap: true", "choc_v2_support: true"]),
}
HOTSWAP = True   # solder-pad variants were dropped; every switch is hotswap

# M2 mounting holes. Keep in sync with `_mount_holes` in config.yaml (same refs and shifts).
HOLES = [
    ("matrix_outer_top", "[kx/2, -ky/2]"),
    ("matrix_ring_top", "[kx/2, -ky/2]"),
    ("matrix_index_top", "[kx/2, -ky/2 - 1]"),
    ("thumbs_t_mid_cluster", "[kx/2 + 1, ky/2 * 0.4]"),
    ("lower_l_outer_low", "[kx/2, ky/2]"),
    ("lower_l_ring_low", "[kx/2, ky/2]"),
    # cover holes (MCU / USB-C cover), all from matrix_inner_top
    ("matrix_inner_top", "[mcu_x - cover_hole_dx, mcu_zero_y + cover_hole_dy0]"),
    ("matrix_inner_top", "[mcu_x + cover_hole_dx, mcu_zero_y + cover_hole_dy0]"),
    ("matrix_inner_top", "[kx/2 + pad/2 + cover_hole_left, link_y - cover_hole_dy]"),
]

out = []
w = out.append
w("pcbs:")
w("  # 4 switch types x 1 MCU = 4 PCBs (hotswap only), named")
w("  #   corne_<switch>_zero")
w("  # Generated by tools/gen_pcbs.py; editing this file by hand is fine too.")
w("  # Shared parts use YAML anchors (&name / *name), defined at first use.")
w("  # Nets: columns outer/pinky/ring/middle/index/inner, rows top/home/bottom/thumb, `link` (USB-C D+),")
w("  # LED chain led_data -> led_1 ... led_24 (see the per-key led_in/led_out in `points`).")
w("")

defined = set()


def block(anchor, header_lines):
    """Emit `<header>: &anchor` first time, `<header>: *anchor` afterwards."""
    key = header_lines[0]
    if anchor in defined:
        w(f"      {key.strip()[:-1] if key.strip().endswith(':') else key.strip()}: *{anchor}")
        return False
    defined.add(anchor)
    w(f"      {key.strip()[:-1]}: &{anchor}" if key.strip().endswith(":") else f"      {key}")
    return True


for sname, sw in SWITCHES.items():
    for hot in (HOTSWAP,):
        for cname, mcu in MCUS.items():
            fam = sw["family"]
            w(f"  corne_{sname}_{cname}:")
            w("    template: kicad8")
            w("    outlines:")
            w("      main:")
            w("        outline: _board")
            w("    footprints:")
            w("      switch:")
            w(f"        what: {sw['what']}")
            w("        where: true")
            w("        params:")
            w('          from: "{{column_net}}"')
            w('          to: "{{colrow}}"')
            w(f"          hotswap: {'true' if hot else 'false'}")
            w("          reversible: true")
            for e in sw["extra"]:
                w(f"          {e}")
            # diode (through-hole), one anchor per switch family
            da = f"diode_{fam}"
            if da in defined:
                w(f"      diode: *{da}")
            else:
                defined.add(da)
                w(f"      diode: &{da}")
                w("        what: ceoloide/diode_tht_sod123")
                w("        where: true")
                w("        params:")
                w('          from: "{{colrow}}"')
                w('          to: "{{row_net}}"')
                w("          include_tht: true     # through-hole (DO-35 / 1N4148) pads")
                w("          reversible: true")
                w("        adjust:")
                w(f"          shift: [0, diode_{fam}_y]")
            # mcu: `mcu` on the front layer (left half), `mcu_back` mirrored on the back layer
            # (right half = same PCB flipped). SMD castellation pads only, so the two sets
            # never share plated holes. Populate one set per half.
            for mname, mside in (("mcu", "F"), ("mcu_back", "B")):
                ma = f"{mname}_{cname}"
                if ma in defined:
                    w(f"      {mname}: *{ma}")
                    continue
                defined.add(ma)
                w(f"      {mname}: &{ma}")
                w(f"        # {mcu['note']}")
                w(f"        what: {mcu['what']}")
                w("        where:")
                w("          ref: matrix_inner_top")
                w("        adjust:")
                w(f"          shift: {mcu['shift']}")
                w("        params:")
                w(f"          side: {mside}")
                w("          mount: smd           # smd | th | both")
                for pin, net in mcu["pins"].items():
                    w(f"          {pin}: {net}")
            # leds, one anchor per (mcu, family)
            # Two LEDs per key on the same nets: `led` on the front layer, `led_back` on the
            # back layer. Left half: populate the front set. Right half (the same PCB flipped):
            # populate the back set, which is then on top.
            for lname, lside in (("led", "F"), ("led_back", "B")):
                la = f"{lname}_{cname}_{fam}"
                if la in defined:
                    w(f"      {lname}: *{la}")
                else:
                    defined.add(la)
                    w(f"      {lname}: &{la}")
                    w("        what: custom/led_ws2812b_5050")
                    w("        where: true")
                    w("        params:")
                    w(f"          side: {lside}")
                    w('          din: "{{led_in}}"')
                    w('          dout: "{{led_out}}"')
                    w(f"          vdd: \"{mcu['vdd']}\"")
                    w("        adjust:")
                    w(f"          shift: [0, led_{fam}_y]")
            # USB-C link module (4-pin breakout plugged in via a header): V -> MCU 5V rail,
            # D+ -> `link` (single-wire serial), G -> GND, D- unused. Front and back sets use
            # different holes; populate only one (left half front, right half back).
            for lname, lside, ldx in (("link", "F", "0"), ("link_back", "B", "link_back_dx")):
                la = f"{lname}_{cname}"
                if la in defined:
                    w(f"      {lname}: *{la}")
                else:
                    defined.add(la)
                    w(f"      {lname}: &{la}")
                    w("        what: custom/usbc_breakout_4pin")
                    w("        where:")
                    w("          ref: matrix_inner_top")
                    w("        adjust:")
                    w(f"          shift: [link_pin_x + {ldx}, link_y]")
                    w("        params:")
                    w(f"          side: {lside}")
                    w(f"          vbus: \"{mcu['vdd']}\"")
                    w("          dp: link")
            for n, (href, hshift) in enumerate(HOLES, 1):
                hn = f"hole_{n}"
                if hn in defined:
                    w(f"      {hn}: *{hn}")
                else:
                    defined.add(hn)
                    w(f"      {hn}: &{hn}")
                    w("        what: ceoloide/mounting_hole_npth")
                    w("        where:")
                    w(f"          ref: {href}")
                    w("        adjust:")
                    w(f"          shift: {hshift}")
                    w("        params:")
                    w("          hole_size: hole_pcb")
                    w("          hole_drill: hole_pcb")
            w("")

text = CONFIG.read_text()
i = text.index("\npcbs:\n")
CONFIG.write_text(text[: i + 1] + "\n".join(out).rstrip() + "\n")
print("wrote", len([l for l in out if l.startswith("  corne_")]), "pcbs")
